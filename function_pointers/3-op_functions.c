/**
 * op_add - adds the ints
 * 
 * @a: the first int
 * @b: the 2nd int
 *
 * Return: the result
 */
int op_add(int a, int b)
{
	return (a + b);
}
/**
 * op_sub - subtracts the ints
 *
 * @a: the first int
 * @b: the 2nd int
 *
 * Return: the result
 */
int op_sub(int a, int b)
{
	return (a - b);
}
/**
 * op_mul - multiplies the ints
 *
 * @a: the first int
 * @b: the 2nd int
 *
 * Return: the result
 */
int op_mul(int a, int b)
{
	return (a * b);
}
/**
 * op_div - divides the ints
 *
 * @a: the first int
 * @b: the 2nd int
 *
 * Return: the result
 */
int op_div(int a, int b)
{
	return (a / b);
}
/**
 * op_mod - mods the ints
 *
 * @a: the first int
 * @b: the 2nd int
 *
 * Return: the result
 */
int op_mod(int a, int b)
{
	return (a % b);
}
